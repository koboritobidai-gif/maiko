/**
 * 入社決定の入金予定(見込み)の手動補正。
 *
 * 「入社決定の入金予定(見込み)」(placement-data.ts)は、KPI表.xlsxの入社日確定者×企業一覧シートの
 * 契約条件×Slack「#求職者」スレッドの労働条件通知書(年収)から報酬を自動計算する。自動抽出が誤る
 * ケースや、条件付き契約(未経験/経験者・職種別など)で経営者が判断した金額は、ここへ追記して上書きする
 * (kpi-adjustments.ts と同じ「コードに手動補正を書く」運用)。
 *
 * - 照合キーは氏名(空白・「様」の有無は無視)。同姓同名がいる場合は企業名違いの別人の可能性があるため、
 *   必要になった時点で company フィールドの追加を検討すること。
 * - feeYen があれば最優先で見込み報酬として確定表示する(税抜の額面)。
 * - annualIncomeYen があれば年収として扱い、契約条件の率を掛けて見込み報酬を算出する
 *   (労働条件通知書がSlackに無い・読み取れない場合に年収だけ補う用途)。
 * - note には根拠(いつ誰が確認したか)を書く。画面にも補正の旨が表示される。
 */
export interface PlacementFeeOverride {
  /** 求職者の氏名(KPI表の表記。空白の有無は問わない)。 */
  name: string;
  /** 年収(円)。契約条件が「率」の場合、この年収に率を掛けて見込み報酬とする。 */
  annualIncomeYen?: number;
  /** 見込み報酬(円・税抜)。指定すると契約条件・年収の自動計算より優先する。 */
  feeYen?: number;
  /** 補正の根拠(例: 「経営者確認 2026-11-02 経験者区分のため35%、年収480万円」)。 */
  note: string;
}

